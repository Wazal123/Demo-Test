def calcular_area_rectangulo(base, altura):
    """
    Calcula el área de un rectángulo dados su base y su altura.
    """
    area = base * altura
    return area

def sumar(a, b):
    """
    Recibe dos números y devuelve su suma.
    """
    resultado = a + b
    return resultado


def restar(a, b):
    """
    Recibe dos números y devuelve su resta (a menos b).
    """
    resultado = a - b
    return resultado

